from typing import Protocol
from flightzero.domain.models import Flight, Reservation


class ReservationRepository(Protocol):
    def list_flights(self) -> dict[str, Flight]: ...
    def list_reservations(self) -> list[Reservation]: ...
    def book(self, flight_id: str, seat_id: str) -> Reservation: ...
    def cancel(self, reservation_id: str) -> Reservation: ...
    def availability(self, flight_id: str) -> list[str]: ...
